//! Persivio desktop app: a Tauri v2 shell over `pv-engine` (ADR-018).
//!
//! - `setup` starts the engine on the shared data directory and keeps it in
//!   [`AppState`]; if that fails (e.g. the CLI holds the directory) the app still opens
//!   and the UI shows why.
//! - Commands ([`commands`]) are typed with specta; the TypeScript bindings are
//!   regenerated on every debug run (and checked by a test).
//! - Progress goes through a channel at ≤ 4 Hz, other events as typed app events
//!   ([`forward`]).
//! - On exit the engine is shut down gracefully, so running downloads checkpoint.

pub mod api;
pub mod commands;
pub mod dto;
pub mod error;
pub mod forward;
pub mod ops;

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};

use anyhow::Context as _;
use pv_engine::{DataDir, Engine, EngineConfig};
use tauri::{Manager, RunEvent};
use tauri_specta::{Event as _, collect_commands, collect_events};

use crate::api::EngineApi;
pub use crate::commands::AppState;
use crate::dto::EngineUiEvent;

/// Where the generated TypeScript bindings live.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/api/bindings.ts");

/// The specta builder listing every command and event. Shared by the app and the
/// bindings test so the two can never disagree.
#[must_use]
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::list_tasks,
            commands::add_task,
            commands::pause_task,
            commands::resume_task,
            commands::cancel_task,
            commands::remove_task,
            commands::pause_all,
            commands::resume_all,
            commands::move_task,
            commands::select_files,
            commands::get_settings,
            commands::set_settings,
            commands::subscribe_progress,
            commands::default_download_dir,
            commands::reveal_task,
            commands::get_task_detail,
            commands::inspect_torrent,
        ])
        .events(collect_events![EngineUiEvent])
        // Sizes/speeds are u64 byte counts, exact as JS numbers up to 8 PiB (ADR-018).
        .dangerously_cast_bigints_to_number()
        // One TypeScript type per Rust type (optional fields are `T | null`, sent explicitly).
        .disable_serde_phases()
}

/// Writes the TypeScript bindings to `path`.
///
/// # Errors
/// If export or writing fails.
pub fn export_bindings(path: &std::path::Path) -> anyhow::Result<()> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta from apps/desktop/src-tauri. Do not edit.\n"),
            path,
        )
        .with_context(|| format!("cannot export bindings to {}", path.display()))
}

/// Starts the engine on the data directory: `PERSIVIO_DATA_DIR` if set (tests, portable
/// use), else the OS default shared with the CLI.
fn start_engine() -> anyhow::Result<(Arc<dyn EngineApi>, DataDir)> {
    let path = match std::env::var_os("PERSIVIO_DATA_DIR") {
        Some(dir) => dir.into(),
        None => DataDir::default_path()?,
    };
    let data_dir = DataDir::open(path)?;
    let engine =
        tauri::async_runtime::block_on(Engine::start(EngineConfig::new(data_dir.db_path())))
            .context("cannot start the download engine")?;
    Ok((Arc::new(engine), data_dir))
}

/// Runs the app until the user quits.
///
/// # Errors
/// If Tauri cannot start (missing webview runtime, invalid configuration).
pub fn run() -> anyhow::Result<()> {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    if let Err(e) = export_bindings(std::path::Path::new(BINDINGS_PATH)) {
        eprintln!("{e:#}");
    }

    let app = tauri::Builder::default()
        // First, so a second launch exits before starting anything.
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }))
        .plugin(
            tauri_plugin_log::Builder::new()
                .level(log_level())
                // Dependencies are chatty (the DHT logs every packet): warnings and up only.
                .filter(|meta| {
                    let ours = meta.target().starts_with("persivio")
                        || meta.target().starts_with("pv_");
                    ours || meta.level() <= tauri_plugin_log::log::Level::Warn
                })
                .build(),
        )
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let engine = match start_engine() {
                Ok((engine, data_dir)) => {
                    // The lock lives as long as the app.
                    app.manage(data_dir);
                    let handle = app.handle().clone();
                    tauri::async_runtime::spawn(forward::forward_events(
                        engine.subscribe(),
                        move |event| {
                            if let Err(e) = event.emit(&handle) {
                                tracing::warn!("cannot emit engine event: {e}");
                            }
                        },
                    ));
                    Ok(engine)
                }
                Err(e) => {
                    tracing::error!("{e:#}");
                    Err(format!("{e:#}"))
                }
            };
            app.manage(AppState::new(engine));
            Ok(())
        })
        .build(tauri::generate_context!())
        .context("cannot start the app")?;

    let shutting_down = AtomicBool::new(false);
    app.run(move |app, event| {
        if let RunEvent::ExitRequested { api, .. } = event {
            // Let running downloads checkpoint before the process ends; the second
            // request (from `app.exit` below) goes through.
            if shutting_down.swap(true, Ordering::SeqCst) {
                return;
            }
            if let Some(engine) = app.state::<AppState>().running_engine() {
                api.prevent_exit();
                let app = app.clone();
                tauri::async_runtime::spawn(async move {
                    engine.shutdown().await;
                    app.exit(0);
                });
            }
        }
    });
    Ok(())
}

fn log_level() -> tauri_plugin_log::log::LevelFilter {
    if cfg!(debug_assertions) {
        tauri_plugin_log::log::LevelFilter::Debug
    } else {
        tauri_plugin_log::log::LevelFilter::Info
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The committed bindings must match the Rust types; run the app in debug mode (or
    /// this test with `PERSIVIO_UPDATE_BINDINGS=1`) to regenerate them.
    #[test]
    fn bindings_are_up_to_date() {
        let committed = std::path::Path::new(BINDINGS_PATH);
        if std::env::var_os("PERSIVIO_UPDATE_BINDINGS").is_some() {
            export_bindings(committed).unwrap();
        }
        let dir = tempfile::tempdir().unwrap();
        let fresh = dir.path().join("bindings.ts");
        export_bindings(&fresh).unwrap();
        let normalize = |s: String| s.replace("\r\n", "\n");
        assert_eq!(
            normalize(std::fs::read_to_string(committed).unwrap_or_default()),
            normalize(std::fs::read_to_string(&fresh).unwrap()),
            "src/lib/api/bindings.ts is stale: run `PERSIVIO_UPDATE_BINDINGS=1 cargo test -p persivio-desktop bindings`"
        );
    }
}
