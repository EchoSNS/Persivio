/// Where the generated TypeScript bindings live.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/api/bindings.ts");

/// The specta builder listing every command and event. Shared by the app and the
/// bindings test so the two can never disagree.
#[must_use]
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::list_tasks,
            commands::add_task,
            commands::pause_task,
            commands::resume_task,
            commands::cancel_task,
            commands::remove_task,
            commands::pause_all,
            commands::resume_all,
            commands::move_task,
            commands::select_files,
            commands::get_settings,
            commands::set_settings,
            commands::subscribe_progress,
            commands::default_download_dir,
            commands::reveal_task,
            commands::get_task_detail,
            commands::inspect_torrent,
            commands::take_external_requests,
            commands::bridge_status,
            commands::new_bridge_token,
            commands::release_notes,
            commands::app_version,
            commands::check_for_update,
            commands::install_update,
            commands::diagnostics_report,
            commands::save_diagnostics,
            commands::open_logs_folder,
        ])
        .events(collect_events![
            EngineUiEvent,
            dto::ExternalRequestsEvent,
            dto::ClipboardLinksEvent,
            updates::UpdateAvailableEvent
        ])
        // Sizes/speeds are u64 byte counts, exact as JS numbers up to 8 PiB (ADR-018).
        .dangerously_cast_bigints_to_number()
        // One TypeScript type per Rust type (optional fields are `T | null`, sent explicitly).
        .disable_serde_phases()
}

/// Writes the TypeScript bindings to `path`.
///
/// # Errors
/// If export or writing fails.
pub fn export_bindings(path: &std::path::Path) -> anyhow::Result<()> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta from apps/desktop/src-tauri. Do not edit.\n"),
            path,
        )
        .with_context(|| format!("cannot export bindings to {}", path.display()))
}

/// Starts the engine on the data directory: `PERSIVIO_DATA_DIR` if set (tests, portable
/// use), else the OS default shared with the CLI.
fn start_engine() -> anyhow::Result<(Arc<dyn EngineApi>, DataDir)> {
    let path = match std::env::var_os("PERSIVIO_DATA_DIR") {
        Some(dir) => dir.into(),
        None => DataDir::default_path()?,
    };
    let data_dir = DataDir::open(path)?;
    let engine =
        tauri::async_runtime::block_on(Engine::start(EngineConfig::new(data_dir.db_path())))
            .context("cannot start the download engine")?;
    Ok((Arc::new(engine), data_dir))
}

/// Runs the app until the user quits.
///
/// # Errors
/// If Tauri cannot start (missing webview runtime, invalid configuration).
pub fn run() -> anyhow::Result<()> {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    if let Err(e) = export_bindings(std::path::Path::new(BINDINGS_PATH)) {
        eprintln!("{e:#}");
    }

    let app = tauri::Builder::default()
        // First, so a second launch exits before starting anything. Its arguments (a
        // magnet link from the browser, an opened .torrent) come here.
        .plugin(tauri_plugin_single_instance::init(|app, args, _cwd| {
            let view = external::resolve(external::classify_args(args.iter().skip(1)));
            if view.is_empty() {
                desktop::show_main_window(app);
            } else {
                desktop::handle_external(app, view);
            }
        }))
        .plugin(
            tauri_plugin_log::Builder::new()
                .level(log_level())
                // Rolling: at most about 10 MB, and never only a few minutes of history.
                .max_file_size(2 * 1024 * 1024)
                .rotation_strategy(tauri_plugin_log::RotationStrategy::KeepSome(4))
                // Dependencies are chatty (the DHT logs every packet): warnings and up only.
                .filter(|meta| {
                    let ours = meta.target().starts_with("persivio")
                        || meta.target().starts_with("pv_");
                    // An unreachable tracker warns several times a minute.
                    let noisy = meta.target().starts_with("librqbit_tracker_comms");
                    ours || (meta.level() <= tauri_plugin_log::log::Level::Warn && !noisy)
                })
                .build(),
        )
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            Some(vec![desktop::MINIMIZED_ARG]),
        ))
        .plugin(tauri_plugin_clipboard_manager::init())
        .plugin(tauri_plugin_deep_link::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .invoke_handler(builder.invoke_handler())
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event
                && window.label() == "main"
                && window
                    .try_state::<desktop::Desktop>()
                    .is_some_and(|d| d.settings.borrow().close_to_tray)
            {
                api.prevent_close();
                let _ = window.hide();
            }
        })
        .setup(move |app| {
            builder.mount_events(app);
            setup(app);
            Ok(())
        })
        .build(tauri::generate_context!())
        .context("cannot start the app")?;

    let shutting_down = AtomicBool::new(false);
    app.run(move |app, event| match event {
        RunEvent::ExitRequested { api, .. } => {
            // Let running downloads checkpoint before the process ends; the second
            // request (from `app.exit` below) goes through.
            if shutting_down.swap(true, Ordering::SeqCst) {
                return;
            }
            if let Some(engine) = app.state::<AppState>().running_engine() {
                api.prevent_exit();
                let app = app.clone();
                tauri::async_runtime::spawn(async move {
                    engine.shutdown().await;
                    app.exit(0);
                });
            }
        }
        // macOS delivers magnet links and opened .torrent files as events, not arguments.
        #[cfg(target_os = "macos")]
        RunEvent::Opened { urls } => {
            let view =
                external::resolve(external::classify_args(urls.iter().map(url::Url::as_str)));
            desktop::handle_external(app, view);
        }
        #[cfg(target_os = "macos")]
        RunEvent::Reopen { .. } => desktop::show_main_window(app),
        _ => {}
    });
    Ok(())
}

/// Starts the engine and the desktop integration. Never fails: without an engine the app
/// still opens (and quits from the tray) and the UI explains the problem.
fn setup(app: &mut tauri::App) {
    let handle = app.handle().clone();
    let started = start_engine();
    let (engine, settings, tasks) = match started {
        Ok((engine, data_dir)) => {
            // The lock lives as long as the app.
            app.manage(data_dir);
            let settings = tauri::async_runtime::block_on(engine.settings()).unwrap_or_default();
            let tasks = tauri::async_runtime::block_on(engine.list()).unwrap_or_default();
            let emitter = handle.clone();
            tauri::async_runtime::spawn(forward::forward_events(
                engine.subscribe(),
                move |event| {
                    if let Err(e) = event.emit(&emitter) {
                        tracing::warn!("cannot emit engine event: {e}");
                    }
                },
            ));
            (Ok(engine), settings, tasks)
        }
        Err(e) => {
            tracing::error!("{e:#}");
            (
                Err(format!("{e:#}")),
                pv_core::Settings::default(),
                Vec::new(),
            )
        }
    };

    let desktop = desktop::Desktop::new(settings.desktop.clone());
    let settings_rx = desktop.settings.subscribe();
    app.manage(desktop);
    for problem in desktop::apply_os_settings(&handle, &settings.desktop) {
        tracing::warn!("{problem}");
    }
    if let Err(e) = desktop::build_tray(&handle) {
        tracing::warn!("no tray icon: {e}");
    }
    app.manage(updates::Updates::default());
    if let Ok(engine) = &engine {
        tauri::async_runtime::spawn(bridge::supervise(
            settings_rx.clone(),
            Arc::clone(engine),
            pv_engine::os_download_dir(),
            Arc::clone(&app.state::<desktop::Desktop>().bridge),
        ));
    }
    // Release builds check for updates at startup (setting); the UI offers to install.
    if !cfg!(debug_assertions) && settings.desktop.check_for_updates {
        let checker = handle.clone();
        tauri::async_runtime::spawn(async move {
            let updates = checker.state::<updates::Updates>();
            match updates.check(&checker).await {
                Ok(Some(found)) => {
                    if let Err(e) = updates::UpdateAvailableEvent(found).emit(&checker) {
                        tracing::warn!("cannot announce the update: {e}");
                    }
                }
                Ok(None) => {}
                Err(e) => tracing::info!("update check: {e}"),
            }
        });
    }
    if let Ok(engine) = &engine {
        tauri::async_runtime::spawn(integration::run(
            engine.subscribe(),
            settings_rx.clone(),
            integration::Activity::new(&tasks),
            desktop::AppSink::new(handle.clone()),
        ));
    }
    let reader = handle.clone();
    let offerer = handle.clone();
    tauri::async_runtime::spawn(clipboard::watch_clipboard(
        move || {
            use tauri_plugin_clipboard_manager::ClipboardExt as _;
            reader.clipboard().read_text().ok()
        },
        settings_rx,
        move |links| desktop::offer_clipboard_links(&offerer, links),
    ));
    app.manage(AppState::new(engine));

    // The window starts hidden (no flash); autostart keeps it in the tray.
    let args: Vec<String> = std::env::args().skip(1).collect();
    if !args.iter().any(|a| a == desktop::MINIMIZED_ARG) {
        desktop::show_main_window(&handle);
    }
    // Launched by a magnet click or an opened .torrent: queue it for the UI.
    desktop::handle_external(&handle, external::resolve(external::classify_args(&args)));
}

fn log_level() -> tauri_plugin_log::log::LevelFilter {
    if cfg!(debug_assertions) {
        tauri_plugin_log::log::LevelFilter::Debug
    } else {
        tauri_plugin_log::log::LevelFilter::Info
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The committed bindings must match the Rust types; run the app in debug mode (or
    /// this test with `PERSIVIO_UPDATE_BINDINGS=1`) to regenerate them.
    #[test]
    fn bindings_are_up_to_date() {
        let committed = std::path::Path::new(BINDINGS_PATH);
        if std::env::var_os("PERSIVIO_UPDATE_BINDINGS").is_some() {
            export_bindings(committed).unwrap();
        }
        let dir = tempfile::tempdir().unwrap();
        let fresh = dir.path().join("bindings.ts");
        export_bindings(&fresh).unwrap();
        let normalize = |s: String| s.replace("\r\n", "\n");
        assert_eq!(
            normalize(std::fs::read_to_string(committed).unwrap_or_default()),
            normalize(std::fs::read_to_string(&fresh).unwrap()),
            "src/lib/api/bindings.ts is stale: run `PERSIVIO_UPDATE_BINDINGS=1 cargo test -p persivio-desktop bindings`"
        );
    }
}
